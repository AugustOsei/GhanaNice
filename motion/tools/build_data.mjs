/* Turns the source data into src/data/generated.ts for the scenes: the site's Ghana outline
   (the home page's window) and the Larabanga line drawing traced by tools/trace.py.
   Run after changing either: node tools/build_data.mjs */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const motion = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repo = path.resolve(motion, '..');

const mask = fs.readFileSync(path.join(repo, 'dist/assets/maps/ghana-mask.svg'), 'utf8');
const ghana = {
  viewBox: mask.match(/viewBox="([^"]+)"/)[1],
  transform: mask.match(/<path transform="([^"]+)"/)[1],
  d: mask.match(/ d="([^"]+)"/)[1],
};
const traces = { larabanga: JSON.parse(fs.readFileSync(path.join(motion, 'trace/larabanga.json'), 'utf8')) };

const out = `/* Generated by tools/build_data.mjs. Don't hand-edit. */
export const GHANA = ${JSON.stringify(ghana)};
export const TRACES = ${JSON.stringify(traces)};
`;
fs.writeFileSync(path.join(motion, 'src/data/generated.ts'), out);
console.log(`ghana outline, traces: ${Object.keys(traces).join(', ')}; ${(out.length / 1024).toFixed(0)} KB`);
